"""
Scaled test runner for RAG pipeline evaluation.

Features:
- Loads Q&A datasets generated by generate_eval_dataset.py
- Rate-limited API calls with exponential backoff
- Saves progress after each query — resume after interruptions
- Comprehensive reporting with per-category breakdowns
- Supports multiple document sets
"""

import json
import os
import sys
import time
import argparse
from pathlib import Path
from datetime import datetime
from dotenv import load_dotenv

import requests

load_dotenv()

API = os.getenv("API_URL", "http://localhost:8000")
API_KEY = os.getenv("API_KEY", "")

HEADERS = {
    "Content-Type": "application/json",
    "X-API-Key": API_KEY,
}

# Rate limiting
MIN_DELAY = 2.0          # seconds between requests
MAX_DELAY = 60.0          # max backoff delay
BACKOFF_FACTOR = 2.0      # exponential backoff multiplier


def load_dataset(dataset_path: str) -> dict:
    """Load evaluation dataset."""
    with open(dataset_path, "r", encoding="utf-8") as f:
        return json.load(f)


def load_progress(progress_path: str) -> dict:
    """Load saved progress or return empty state."""
    if Path(progress_path).exists():
        with open(progress_path, "r", encoding="utf-8") as f:
            return json.load(f)
    return {"completed": [], "results": [], "errors": []}


def save_progress(progress_path: str, progress: dict):
    """Save progress after each query."""
    with open(progress_path, "w", encoding="utf-8") as f:
        json.dump(progress, f, indent=2, ensure_ascii=False)


def query_api(query: str, retries: int = 3) -> dict | None:
    """Send a query to the RAG API with retry logic."""
    delay = MIN_DELAY

    for attempt in range(retries + 1):
        try:
            response = requests.post(
                f"{API}/api/chat",
                headers=HEADERS,
                json={"query": query},
                timeout=60,
            )

            if response.status_code == 429:
                retry_after = int(response.headers.get("Retry-After", delay))
                print(f"    Rate limited. Waiting {retry_after}s...")
                time.sleep(retry_after)
                delay = min(delay * BACKOFF_FACTOR, MAX_DELAY)
                continue

            if response.status_code != 200:
                print(f"    HTTP {response.status_code}: {response.text[:200]}")
                if attempt < retries:
                    time.sleep(delay)
                    delay = min(delay * BACKOFF_FACTOR, MAX_DELAY)
                    continue
                return None

            return response.json()

        except requests.exceptions.Timeout:
            print(f"    Timeout (attempt {attempt + 1}/{retries + 1})")
            if attempt < retries:
                time.sleep(delay)
                delay = min(delay * BACKOFF_FACTOR, MAX_DELAY)
                continue
            return None

        except requests.exceptions.ConnectionError as e:
            print(f"    Connection error: {e}")
            if attempt < retries:
                time.sleep(delay)
                delay = min(delay * BACKOFF_FACTOR, MAX_DELAY)
                continue
            return None

        except Exception as e:
            print(f"    Unexpected error: {e}")
            return None

    return None


def evaluate_result(question: dict, api_response: dict) -> dict:
    """Evaluate a single API response against expected answer."""
    category = question.get("category", "unknown")
    expected = question.get("expected_answer", "")

    guardrails = api_response.get("guardrails", {})
    classified_as = guardrails.get("classified_as", "unknown")
    answer = api_response.get("answer", "")
    hallucination = api_response.get("hallucination_check")
    citations = api_response.get("citations", [])

    # Evaluation metrics
    result = {
        "question": question["question"],
        "category": category,
        "difficulty": question.get("difficulty", "unknown"),
        "source_file": question.get("source_file", "unknown"),
        "classified_as": classified_as,
        "num_citations": len(citations),
        "answer_length": len(answer),
    }

    # Scope accuracy
    if category == "out_of_scope":
        result["scope_correct"] = (classified_as == "out_of_scope")
    else:
        result["scope_correct"] = (classified_as == "in_scope")

    # Citation coverage (in-scope only)
    if hallucination and category != "out_of_scope":
        result["citation_coverage"] = hallucination.get("citation_coverage", 0)
        result["cited_claims"] = hallucination.get("cited_claims", 0)
        result["uncited_claims"] = len(hallucination.get("uncited_claims", []))
        result["is_suspicious"] = hallucination.get("is_suspicious", False)
    else:
        result["citation_coverage"] = None
        result["cited_claims"] = 0
        result["uncited_claims"] = 0
        result["is_suspicious"] = False

    return result


def print_progress_bar(current, total, bar_length=40):
    """Print a progress bar."""
    fraction = current / total
    filled = int(bar_length * fraction)
    bar = "█" * filled + "░" * (bar_length - filled)
    pct = fraction * 100
    print(f"\r  [{bar}] {current}/{total} ({pct:.1f}%)", end="", flush=True)


def run_evaluation(dataset_path: str, progress_dir: str = "./experiments"):
    """Run the full evaluation with progress saving."""

    dataset = load_dataset(dataset_path)
    questions = dataset["questions"]
    total = len(questions)

    # Progress file
    dataset_name = Path(dataset_path).stem
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    progress_path = f"{progress_dir}/progress_{dataset_name}.json"
    results_path = f"{progress_dir}/results_{dataset_name}_{timestamp}.json"

    Path(progress_dir).mkdir(parents=True, exist_ok=True)

    # Load existing progress
    progress = load_progress(progress_path)
    completed_questions = set(progress["completed"])
    results = progress["results"]
    errors = progress["errors"]

    remaining = [
        (i, q) for i, q in enumerate(questions)
        if q["question"] not in completed_questions
    ]

    print(f"{'='*70}")
    print(f"RAG Pipeline Evaluation")
    print(f"{'='*70}")
    print(f"Dataset:    {dataset_path}")
    print(f"Total:      {total} questions")
    print(f"Completed:  {len(completed_questions)}")
    print(f"Remaining:  {len(remaining)}")
    print(f"Progress:   {progress_path}")
    print(f"{'='*70}")

    if not remaining:
        print("All questions already completed. Generating report...")
        generate_report(results, dataset, results_path)
        return

    # Verify API is up
    try:
        health = requests.get(f"{API}/health", timeout=5)
        if health.status_code != 200:
            print(f"API health check failed: {health.status_code}")
            return
    except Exception as e:
        print(f"Cannot reach API at {API}: {e}")
        print("Start the server first: uvicorn src.api.main:app --reload")
        return

    print(f"\nRunning {len(remaining)} queries...\n")

    start_time = time.time()
    batch_start = time.time()

    for idx, (i, question) in enumerate(remaining):
        q_text = question["question"]
        category = question.get("category", "?")

        # Progress
        done = len(completed_questions) + idx + 1
        print_progress_bar(done, total)
        print(f"  [{category}] {q_text[:50]}...", end="")

        # Query the API
        api_response = query_api(q_text)

        if api_response is None:
            errors.append({
                "question": q_text,
                "error": "API call failed after retries",
                "index": i,
            })
            print(" ✗ FAILED")
        else:
            result = evaluate_result(question, api_response)
            results.append(result)

            cov = result.get("citation_coverage")
            cov_str = f"{cov:.0%}" if cov is not None else "N/A"
            scope_ok = "✓" if result["scope_correct"] else "✗"
            print(f" {scope_ok} cov={cov_str}")

        # Save progress
        completed_questions.add(q_text)
        progress["completed"] = list(completed_questions)
        progress["results"] = results
        progress["errors"] = errors
        save_progress(progress_path, progress)

        # Rate limiting
        time.sleep(MIN_DELAY)

        # Print batch stats every 50 queries
        if (idx + 1) % 50 == 0:
            elapsed = time.time() - batch_start
            qps = 50 / elapsed if elapsed > 0 else 0
            print(f"\n  --- Batch: {qps:.1f} queries/sec, "
                  f"{len(errors)} errors so far ---")
            batch_start = time.time()

    total_time = time.time() - start_time
    print(f"\n\nCompleted in {total_time:.0f}s "
          f"({total_time/60:.1f} min)")

    # Generate final report
    generate_report(results, dataset, results_path)

    # Clean up progress file
    if not errors:
        Path(progress_path).unlink(missing_ok=True)
        print(f"Progress file cleaned up.")


def generate_report(results: list, dataset: dict, output_path: str):
    """Generate comprehensive evaluation report."""

    print(f"\n{'='*70}")
    print("EVALUATION REPORT")
    print(f"{'='*70}")

    total = len(results)
    if total == 0:
        print("No results to report.")
        return

    # Overall metrics
    scope_correct = sum(1 for r in results if r["scope_correct"])
    scope_accuracy = scope_correct / total if total else 0

    # In-scope metrics
    in_scope = [r for r in results if r.get("category") != "out_of_scope"]
    out_scope = [r for r in results if r.get("category") == "out_of_scope"]

    coverages = [r["citation_coverage"] for r in in_scope
                 if r["citation_coverage"] is not None]
    avg_coverage = sum(coverages) / len(coverages) if coverages else 0

    total_cited = sum(r["cited_claims"] for r in in_scope)
    total_uncited = sum(r["uncited_claims"] for r in in_scope)
    total_claims = total_cited + total_uncited
    hallucination_rate = total_uncited / total_claims if total_claims else 0

    suspicious = sum(1 for r in in_scope if r["is_suspicious"])

    print(f"\nOverall ({total} queries)")
    print(f"  Scope accuracy:      {scope_accuracy:.1%} ({scope_correct}/{total})")
    print(f"  In-scope queries:    {len(in_scope)}")
    print(f"  Out-of-scope queries:{len(out_scope)}")

    print(f"\nCitation Metrics (in-scope only)")
    print(f"  Avg coverage:        {avg_coverage:.1%}")
    print(f"  Total cited claims:  {total_cited}")
    print(f"  Total uncited claims:{total_uncited}")
    print(f"  Hallucination rate:  {hallucination_rate:.1%} ({total_uncited}/{total_claims})")
    print(f"  Suspicious answers:  {suspicious}/{len(in_scope)}")

    # Per-category breakdown
    categories = set(r.get("category", "unknown") for r in results)

    print(f"\nPer-Category Breakdown")
    print(f"  {'Category':<15} {'Count':>6} {'Scope%':>7} {'Coverage':>9} {'Halluc%':>8}")
    print(f"  {'─'*15} {'─'*6} {'─'*7} {'─'*9} {'─'*8}")

    for cat in sorted(categories):
        cat_results = [r for r in results if r.get("category") == cat]
        cat_count = len(cat_results)
        cat_scope = sum(1 for r in cat_results if r["scope_correct"])
        cat_scope_pct = cat_scope / cat_count if cat_count else 0

        cat_coverages = [r["citation_coverage"] for r in cat_results
                         if r["citation_coverage"] is not None]
        cat_avg_cov = sum(cat_coverages) / len(cat_coverages) if cat_coverages else 0

        cat_cited = sum(r["cited_claims"] for r in cat_results)
        cat_uncited = sum(r["uncited_claims"] for r in cat_results)
        cat_total = cat_cited + cat_uncited
        cat_halluc = cat_uncited / cat_total if cat_total else 0

        print(f"  {cat:<15} {cat_count:>6} {cat_scope_pct:>6.0%} "
              f"{cat_avg_cov:>8.1%} {cat_halluc:>7.1%}")

    # Per-document breakdown
    sources = set(r.get("source_file", "unknown") for r in results)
    if len(sources) > 1:
        print(f"\nPer-Document Breakdown")
        print(f"  {'Document':<30} {'Count':>6} {'Coverage':>9} {'Halluc%':>8}")
        print(f"  {'─'*30} {'─'*6} {'─'*9} {'─'*8}")

        for src in sorted(sources):
            src_results = [r for r in results if r.get("source_file") == src]
            src_count = len(src_results)

            src_coverages = [r["citation_coverage"] for r in src_results
                             if r["citation_coverage"] is not None]
            src_avg_cov = sum(src_coverages) / len(src_coverages) if src_coverages else 0

            src_cited = sum(r["cited_claims"] for r in src_results)
            src_uncited = sum(r["uncited_claims"] for r in src_results)
            src_total = src_cited + src_uncited
            src_halluc = src_uncited / src_total if src_total else 0

            print(f"  {src:<30} {src_count:>6} {src_avg_cov:>8.1%} {src_halluc:>7.1%}")

    # Worst performing queries
    worst = sorted(
        [r for r in in_scope if r["citation_coverage"] is not None],
        key=lambda r: r["citation_coverage"]
    )[:10]

    if worst and worst[0]["citation_coverage"] < 1.0:
        print(f"\nWeakest Queries (lowest coverage)")
        for r in worst:
            if r["citation_coverage"] < 1.0:
                print(f"  [{r['citation_coverage']:.0%}] [{r['category']}] "
                      f"{r['question'][:60]}")

    # Save full report
    report = {
        "timestamp": datetime.now().isoformat(),
        "summary": {
            "total_queries": total,
            "scope_accuracy": round(scope_accuracy, 4),
            "avg_citation_coverage": round(avg_coverage, 4),
            "hallucination_rate": round(hallucination_rate, 4),
            "suspicious_answers": suspicious,
            "total_cited_claims": total_cited,
            "total_uncited_claims": total_uncited,
        },
        "per_category": {
            cat: {
                "count": len([r for r in results if r.get("category") == cat]),
                "scope_accuracy": round(
                    sum(1 for r in results if r.get("category") == cat and r["scope_correct"])
                    / max(1, len([r for r in results if r.get("category") == cat])), 4
                ),
            }
            for cat in categories
        },
        "results": results,
    }

    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, ensure_ascii=False)

    print(f"\nFull report saved to {output_path}")


def main():
    parser = argparse.ArgumentParser(description="Run RAG evaluation")
    parser.add_argument("--dataset", default="./experiments/eval_dataset.json",
                        help="Path to evaluation dataset JSON")
    parser.add_argument("--output-dir", default="./experiments",
                        help="Directory for results and progress files")
    parser.add_argument("--api-url", default=None,
                        help="API base URL (default: from .env or localhost:8000)")

    args = parser.parse_args()

    if args.api_url:
        global API
        API = args.api_url

    run_evaluation(args.dataset, args.output_dir)


if __name__ == "__main__":
    main()